// 1. Luo kokonaislukutyyppinen muuttuja nimeltä ”eka”
int eka;
// 2. Sijoita muuttujaan "eka" arvo 7
eka = 7;
// 3. Luo kokonaislukutyyppinen muuttuja nimeltä ”toka”
// 4. Sijoita muuttujaan "toka" arvo 3
int toka = 3;
// 5. Luo kokonaislukutyyppinen muuttuja "kolmas", jonka arvo on muuttujan
// "eka" arvo kerrottuna muuttujan "toka" arvolla
int kolmas = eka * toka;
// 6. Tulosta muuttujan "kolmas" arvo
Console.WriteLine(kolmas);